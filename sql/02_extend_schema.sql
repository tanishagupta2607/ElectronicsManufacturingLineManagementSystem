-- Run as EMLS_APP after the eight existing manufacturing tables are present.
-- This script adds authentication, customer orders and status history.
-- If a sequence/table already exists, skip its CREATE statement.

CREATE SEQUENCE USER_ACCOUNT_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE CUSTOMER_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE CUSTOMER_ORDER_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE ORDER_ITEM_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE ORDER_STATUS_HISTORY_SEQ START WITH 1000 INCREMENT BY 1 NOCACHE;

CREATE TABLE CUSTOMER (
    CUSTOMER_ID NUMBER(10) PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(120) NOT NULL UNIQUE,
    PHONE VARCHAR2(20),
    ADDRESS VARCHAR2(250),
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE USER_ACCOUNT (
    USER_ID NUMBER(10) PRIMARY KEY,
    USERNAME VARCHAR2(60) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(300) NOT NULL,
    ROLE VARCHAR2(10) NOT NULL CHECK (ROLE IN ('ADMIN','STAFF','CLIENT')),
    CUSTOMER_ID NUMBER(10),
    ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL CHECK (ACTIVE IN ('Y','N')),
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_USER_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID),
    CONSTRAINT CK_USER_ROLE_CUSTOMER CHECK (
      (ROLE = 'CLIENT' AND CUSTOMER_ID IS NOT NULL) OR
      (ROLE IN ('ADMIN','STAFF') AND CUSTOMER_ID IS NULL)
    )
);

CREATE TABLE CUSTOMER_ORDER (
    ORDER_ID NUMBER(10) PRIMARY KEY,
    CUSTOMER_ID NUMBER(10) NOT NULL,
    ORDER_DATE DATE DEFAULT SYSDATE NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL
      CHECK (STATUS IN ('PENDING','APPROVED','REJECTED','IN_PRODUCTION','READY','COMPLETED')),
    TOTAL_AMOUNT NUMBER(12,2) NOT NULL CHECK (TOTAL_AMOUNT >= 0),
    CONSTRAINT FK_ORDER_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
);

CREATE TABLE ORDER_ITEM (
    ORDER_ITEM_ID NUMBER(10) PRIMARY KEY,
    ORDER_ID NUMBER(10) NOT NULL,
    PRODUCT_ID NUMBER(10) NOT NULL,
    QUANTITY NUMBER(10) NOT NULL CHECK (QUANTITY > 0),
    UNIT_PRICE NUMBER(12,2) NOT NULL CHECK (UNIT_PRICE >= 0),
    CONSTRAINT FK_ITEM_ORDER FOREIGN KEY (ORDER_ID) REFERENCES CUSTOMER_ORDER(ORDER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ITEM_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID)
);

CREATE TABLE ORDER_STATUS_HISTORY (
    HISTORY_ID NUMBER(10) PRIMARY KEY,
    ORDER_ID NUMBER(10) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    UPDATED_BY NUMBER(10) NOT NULL,
    NOTE VARCHAR2(500),
    UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_HISTORY_ORDER FOREIGN KEY (ORDER_ID) REFERENCES CUSTOMER_ORDER(ORDER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_HISTORY_USER FOREIGN KEY (UPDATED_BY) REFERENCES USER_ACCOUNT(USER_ID)
);

CREATE INDEX IDX_ORDER_CUSTOMER_DATE ON CUSTOMER_ORDER(CUSTOMER_ID, ORDER_DATE);
CREATE INDEX IDX_COMPONENT_QUANTITY ON COMPONENT(QUANTITY);
CREATE INDEX IDX_HISTORY_ORDER_DATE ON ORDER_STATUS_HISTORY(ORDER_ID, UPDATED_AT);

